const freqOriginal = frequency(filtered);
const freqEncrypted = frequency(encrypted);

const sortedChars = Object.keys(freqOriginal).sort((a,b)=>freqOriginal[b]-freqOriginal[a]);

async function writeExcel() {
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet("Symbol Frequency");

  ws.columns = [
    { header: "Original Char", key: "orig_char", width: 15 },
    { header: "Original Freq", key: "orig_freq", width: 15 },
    { header: "Encrypted Char", key: "enc_char", width: 15 },
    { header: "Encrypted Freq", key: "enc_freq", width: 15 },
  ];

  for (let c of sortedChars) {
    ws.addRow({
      orig_char: c,
      orig_freq: freqOriginal[c],
      enc_char: encrypt(c),
      enc_freq: freqEncrypted[encrypt(c)] || 0
    });
  }

  await wb.xlsx.writeFile("Отчёт.xlsx");
  console.log("Excel файл создан: symbol_frequency.xlsx");
}

